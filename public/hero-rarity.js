const aliases={common:'common',siradan:'common',ordinary:'common',advanced:'advanced',gelismis:'advanced',rare:'rare',nadir:'rare',legendary:'legendary',efsanevi:'legendary'};
export function normalizeHeroRarity(value){
 const key=String(value??'').trim().toLocaleLowerCase('tr').normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/ı/g,'i');
 return aliases[key]||null;
}
const rosterHero=hero=>roster[hero?.id]||Object.values(roster).find(([name])=>name===hero?.name);
export function heroPortraitSource(hero){return rosterHero(hero)?.[2]||null;}
export function heroRarity(hero){
 const known=rosterHero(hero);
 return normalizeHeroRarity(known?.[1])||normalizeHeroRarity(hero?.rarity)||'common';
}
const labels={common:['Sıradan','Common'],advanced:['Gelişmiş','Advanced'],rare:['Nadir','Rare'],legendary:['Efsanevi','Legendary']};
export function heroRarityLabel(rarity,language='tr'){return labels[normalizeHeroRarity(rarity)||'common'][language==='en'?1:0];}
const paths={advanced:'M12 2 15 8.5 22 9.5 17 14.5 18 22 12 18.5 6 22 7 14.5 2 9.5 9 8.5Z',rare:'M12 2 22 12 12 22 2 12Z M12 2 7 12 12 22 17 12Z M2 12H22',legendary:'M3 7 7 11 12 3 17 11 21 7 19 18H5Z M5 21H19'};
export function applyHeroRarity(document,portrait,hero){
 const rarity=heroRarity(hero);portrait.dataset.rarity=rarity;
 if(portrait._rarityKey!==rarity){
  portrait._rarityBadge?.remove();portrait._rarityBadge=null;
  if(paths[rarity]){
   const badge=document.createElement('span');badge.className='hero-rarity-badge';badge.setAttribute('aria-hidden','true');
   badge.innerHTML='<svg viewBox="0 0 24 24" focusable="false" aria-hidden="true"><path d="'+paths[rarity]+'"/></svg>';
   portrait.append(badge);portrait._rarityBadge=badge;
  }
  portrait._rarityKey=rarity;
 }
 return heroRarityLabel(rarity,document.documentElement?.lang);
}

